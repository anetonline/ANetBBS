"""Regression test for a real security/reliability audit finding
(2026-10-22): install.sh and update.sh both generate systemd units with
ProtectHome=yes (hides /home, /root, /run/user from the service
entirely), but only ever carved back $INSTALL_DIR/data and
$INSTALL_DIR/logs via ReadWritePaths= -- never the venv/code tree
itself, and the terminal unit (anetbbs.service) had NO ReadWritePaths=
at all despite also setting ProtectHome=yes.

This is harmless for the default /opt/anetbbs install (entirely outside
ProtectHome's scope), but a REAL install under /home -- a common,
supported choice, and exactly how the project's own live production
instance is deployed -- would have its own venv/binary masked out from
under it by ProtectHome, failing every single generated unit's
ExecStart with ENOENT. A fresh install under /home, or any scenario
where one of the 5 generated unit files is missing and gets
regenerated by install.sh/update.sh's own "self-heal if missing" logic,
would produce a BBS that cannot start at all.

Two separate carve-outs are used, not one, after a follow-up review
asked whether the first draft of this fix (ReadWritePaths= over the
WHOLE tree, for every unit) granted more write access than necessary.
It did: only anetbbs-web.service actually needs full read-write across
its whole install tree under /home (matching its EXISTING non-/home
behavior -- its own ProtectSystem=full comment already explains this is
for the Service Control Center's self-upgrade feature, which writes
across the whole tree via git pull/docker build, not just data/). The
other four generated units (anetbbs/terminal, anetbbs-mrc-bridge,
anetbbs-binkp, anetbbs-finger) never write to their own code -- they
only need it back as READ-only (via ReadOnlyPaths=) plus their
already-existing, UNCHANGED narrow ReadWritePaths=$INSTALL_DIR/data
$INSTALL_DIR/logs. systemd applies the more specific, later-listed path
when ReadOnlyPaths= and ReadWritePaths= overlap, so listing the
ReadOnlyPaths= line first and the narrower ReadWritePaths= line second
(as both scripts do) makes data/logs end up writable while the rest of
the tree stays read-only.

This exact combination (ProtectHome=yes + ReadOnlyPaths=<whole tree> +
ReadWritePaths=<data and logs subdirs>) was verified empirically, not
just reasoned about, via a real unprivileged mount+user namespace
reproduction of systemd's own ProtectHome mechanism in this project's
own dev sandbox (not included here as an automated test, since
unprivileged user-namespace mount operations are not reliably available
in every CI/container environment this suite runs in -- see this
project's own established lesson about environment-dependent test
fragility). Result: EXEC_OK, READ of the code tree OK, WRITE to data/
OK, and WRITE to the code tree correctly FAILED with "Read-only file
system" -- exactly the intended behavior.

These tests actually EXTRACT the real case-statement text from the live
script files and RUN it via a real bash subprocess with a controlled
$INSTALL_DIR, rather than reimplementing the logic in Python (which
could silently drift from what the shipped script actually does and
give false confidence) or only checking that some static string is
present (which would catch a typo but not a logic bug in which branch
fires for which path).
"""
import re
import subprocess
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

_CASE_BLOCK_RE = re.compile(
    r'_INSTALL_DIR_REAL="\$\(realpath -m "\$INSTALL_DIR".*?esac',
    re.DOTALL,
)


def _extract_case_block(script_text):
    m = _CASE_BLOCK_RE.search(script_text)
    assert m, 'could not find the RWPATHS/HOME_ROPATH case-statement block'
    return m.group(0)


def _resolve_vars(script_text, install_dir):
    """Runs the REAL extracted case-statement from the script (not a
    reimplementation) in an actual bash subprocess with the given
    INSTALL_DIR, and returns (RWPATHS, HOME_ROPATH)."""
    case_block = _extract_case_block(script_text)
    probe = (f'INSTALL_DIR={install_dir!r}\n{case_block}\n'
             'printf \'%s\\x1f%s\' "$RWPATHS" "$HOME_ROPATH"\n')
    result = subprocess.run(
        ['bash', '-c', probe], capture_output=True, text=True, timeout=10)
    assert result.returncode == 0, (
        f'case-statement probe failed: {result.stderr}')
    rwpaths, _, home_ropath = result.stdout.partition('\x1f')
    return rwpaths, home_ropath


def _extract_heredoc(script_text, unit_name):
    pattern = re.compile(
        r'cat > .*' + re.escape(unit_name) + r'\.service << SVCEOF\n'
        r'(.*?)\nSVCEOF',
        re.DOTALL,
    )
    m = pattern.search(script_text)
    assert m, f'could not find a {unit_name}.service heredoc'
    return m.group(1)


def _render_heredoc(script_text, unit_name, install_dir, venv_dir,
                    rwpaths, home_ropath):
    """Renders a heredoc body the way bash's unquoted <<SVCEOF actually
    would, substituting the handful of variables these units reference
    -- so a test can assert on the REAL FINAL unit-file text a sysop
    would get, not just the pre-substitution template."""
    body = _extract_heredoc(script_text, unit_name)
    body = body.replace('${HOME_ROPATH:+ReadOnlyPaths=$HOME_ROPATH}',
                        f'ReadOnlyPaths={home_ropath}' if home_ropath else '')
    body = body.replace('$RWPATHS', rwpaths)
    body = body.replace('$INSTALL_DIR', install_dir)
    body = body.replace('$VENV_DIR', venv_dir)
    return body


class RWPathsAndHomeRoPathResolutionTests(unittest.TestCase):
    """Exercises the real case-statement logic with various INSTALL_DIR
    values, for both install.sh and update.sh independently (they carry
    separate copies of this block, not a shared library)."""

    @classmethod
    def setUpClass(cls):
        cls.install_sh = (REPO_ROOT / 'install.sh').read_text()
        cls.update_sh = (REPO_ROOT / 'update.sh').read_text()

    def test_default_opt_install_keeps_the_original_narrow_rwpaths_and_no_ropath(self):
        """No regression for the common case: RWPATHS is the exact same
        value as before this fix existed, and HOME_ROPATH is empty (so
        the conditional ReadOnlyPaths= line on the other 4 units is
        omitted entirely)."""
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/opt/anetbbs')
            self.assertEqual(rw, '/opt/anetbbs/data /opt/anetbbs/logs')
            self.assertEqual(ro, '')

    def test_home_rooted_install_gets_full_rwpaths_and_a_readonly_tree(self):
        """The actual live-deployment shape (/home/stingray/anetbbs):
        RWPATHS (for the self-upgrading web unit) is the whole tree,
        and HOME_ROPATH (for the other 4 units' ReadOnlyPaths=) is also
        the whole tree -- both needed so ExecStart can find the venv/
        binary under ProtectHome=yes."""
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/home/stingray/anetbbs')
            self.assertEqual(rw, '/home/stingray/anetbbs')
            self.assertEqual(ro, '/home/stingray/anetbbs')

    def test_different_home_user_also_gets_both(self):
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/home/someoperator/bbs')
            self.assertEqual(rw, '/home/someoperator/bbs')
            self.assertEqual(ro, '/home/someoperator/bbs')

    def test_root_rooted_install_also_gets_both(self):
        """ProtectHome=yes also hides /root -- an install directly
        under it needs the same carve-outs, not just /home."""
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/root/anetbbs')
            self.assertEqual(rw, '/root/anetbbs')
            self.assertEqual(ro, '/root/anetbbs')

    def test_a_path_merely_containing_the_word_home_is_not_mismatched(self):
        """Must not falsely match a path like /opt/home-brew-anetbbs or
        /srv/homebase -- only a real /home/* or /root* prefix."""
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/opt/home-brew-anetbbs')
            self.assertEqual(rw, '/opt/home-brew-anetbbs/data '
                                '/opt/home-brew-anetbbs/logs')
            self.assertEqual(ro, '')
            rw2, ro2 = _resolve_vars(script, '/srv/homebase')
            self.assertEqual(rw2, '/srv/homebase/data /srv/homebase/logs')
            self.assertEqual(ro2, '')

    def test_trailing_slash_and_dotdot_normalization_still_match_home(self):
        """realpath -m should normalize a messier path before the case
        match runs, so a trailing slash or an embedded .. doesn't dodge
        the /home/* pattern, and the normalized form is what both
        variables end up using."""
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/home/stingray/./anetbbs/')
            self.assertEqual(rw, '/home/stingray/anetbbs')
            self.assertEqual(ro, '/home/stingray/anetbbs')


class LeastPrivilegePerUnitTests(unittest.TestCase):
    """Confirms the two carve-outs are assigned to the RIGHT units --
    only the self-upgrading web unit gets full read-write to the whole
    tree; the other four get it back read-only, with their own
    pre-existing narrow data/logs write access unchanged."""

    @classmethod
    def setUpClass(cls):
        cls.install_sh = (REPO_ROOT / 'install.sh').read_text()
        cls.update_sh = (REPO_ROOT / 'update.sh').read_text()

    def test_only_web_unit_uses_the_broad_rwpaths_variable(self):
        non_web_units = ('anetbbs', 'anetbbs-mrc-bridge',
                         'anetbbs-binkp', 'anetbbs-finger')
        for script, name in ((self.install_sh, 'install.sh'),
                             (self.update_sh, 'update.sh')):
            web_body = _extract_heredoc(script, 'anetbbs-web')
            self.assertIn('ReadWritePaths=$RWPATHS', web_body,
                          f'{name}: anetbbs-web should use the broad $RWPATHS')
            for unit in non_web_units:
                body = _extract_heredoc(script, unit)
                self.assertNotIn(
                    'ReadWritePaths=$RWPATHS', body,
                    f'{name}: {unit}.service should NOT get the broad '
                    '$RWPATHS (full read-write over the whole tree) -- '
                    'it never writes to its own code, only data/logs')

    def test_the_four_non_upgrading_units_keep_their_narrow_rw_and_gain_a_conditional_readonly(self):
        units = ('anetbbs', 'anetbbs-mrc-bridge', 'anetbbs-binkp',
                 'anetbbs-finger')
        for script, name in ((self.install_sh, 'install.sh'),
                             (self.update_sh, 'update.sh')):
            for unit in units:
                body = _extract_heredoc(script, unit)
                self.assertIn(
                    'ReadWritePaths=$INSTALL_DIR/data $INSTALL_DIR/logs',
                    body, f'{name}: {unit}.service lost its narrow '
                    'data/logs ReadWritePaths=')
                self.assertIn(
                    '${HOME_ROPATH:+ReadOnlyPaths=$HOME_ROPATH}', body,
                    f'{name}: {unit}.service is missing the conditional '
                    'ReadOnlyPaths= carve-out needed for a /home-rooted '
                    'install')

    def test_readonly_line_precedes_the_narrower_readwrite_line(self):
        """systemd applies the more specific, LATER-listed overlapping
        path -- ReadOnlyPaths=<whole tree> must come before
        ReadWritePaths=<data/logs subdirs> in the unit file, or the
        broader read-only directive would win and make data/logs
        read-only too."""
        units = ('anetbbs', 'anetbbs-mrc-bridge', 'anetbbs-binkp',
                 'anetbbs-finger')
        for script in (self.install_sh, self.update_sh):
            for unit in units:
                body = _extract_heredoc(script, unit)
                ro_pos = body.index('${HOME_ROPATH:+ReadOnlyPaths=$HOME_ROPATH}')
                rw_pos = body.index(
                    'ReadWritePaths=$INSTALL_DIR/data $INSTALL_DIR/logs')
                self.assertLess(ro_pos, rw_pos,
                                f'{unit}: ReadOnlyPaths= must precede the '
                                'narrower ReadWritePaths= so data/logs '
                                'stay writable')

    def test_no_unit_has_the_old_broad_rwpaths_applied_to_non_web_units(self):
        """Guards against a half-applied narrowing: no non-web heredoc
        should still contain a bare ReadWritePaths=$RWPATHS left over
        from the first draft of this fix."""
        units = ('anetbbs', 'anetbbs-mrc-bridge', 'anetbbs-binkp',
                 'anetbbs-finger')
        for script in (self.install_sh, self.update_sh):
            for unit in units:
                body = _extract_heredoc(script, unit)
                self.assertNotIn('ReadWritePaths=$RWPATHS', body)

    def test_terminal_unit_still_has_no_protectsystem(self):
        """The fix must not have accidentally added ProtectSystem= to
        anetbbs.service -- it deliberately has none (door-game
        subprocess paths can live anywhere on disk; DOSBox's JIT needs
        writable+executable memory)."""
        for script in (self.install_sh, self.update_sh):
            body = _extract_heredoc(script, 'anetbbs')
            directive_only = '\n'.join(
                line for line in body.splitlines()
                if not line.lstrip().startswith('#'))
            self.assertNotIn('ProtectSystem=', directive_only)
            self.assertIn('ProtectHome=yes', directive_only)


class RenderedUnitFileContentTests(unittest.TestCase):
    """Renders the actual, final, post-substitution unit-file text for
    a /home-rooted install and checks the real end result a sysop would
    get written to /etc/systemd/system/ -- not just the template."""

    @classmethod
    def setUpClass(cls):
        cls.install_sh = (REPO_ROOT / 'install.sh').read_text()
        cls.update_sh = (REPO_ROOT / 'update.sh').read_text()

    def test_rendered_terminal_unit_for_a_home_install(self):
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/home/stingray/anetbbs')
            rendered = _render_heredoc(
                script, 'anetbbs', '/home/stingray/anetbbs',
                '/home/stingray/anetbbs/venv', rw, ro)
            self.assertIn('ProtectHome=yes', rendered)
            self.assertIn('ReadOnlyPaths=/home/stingray/anetbbs', rendered)
            self.assertIn(
                'ReadWritePaths=/home/stingray/anetbbs/data '
                '/home/stingray/anetbbs/logs', rendered)
            self.assertIn(
                'ExecStart=/home/stingray/anetbbs/venv/bin/anetbbs',
                rendered)

    def test_rendered_web_unit_for_a_home_install_keeps_full_tree_rw(self):
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/home/stingray/anetbbs')
            rendered = _render_heredoc(
                script, 'anetbbs-web', '/home/stingray/anetbbs',
                '/home/stingray/anetbbs/venv', rw, ro)
            self.assertIn('ProtectHome=yes', rendered)
            self.assertIn('ReadWritePaths=/home/stingray/anetbbs', rendered)
            self.assertNotIn('ReadOnlyPaths=', rendered)

    def test_rendered_units_for_the_default_install_are_byte_identical_to_pre_fix(self):
        """The strongest possible no-regression check: for the default
        /opt/anetbbs case, the rendered unit text is IDENTICAL to what
        the pre-fix hardcoded literals would have produced."""
        for script in (self.install_sh, self.update_sh):
            rw, ro = _resolve_vars(script, '/opt/anetbbs')
            for unit in ('anetbbs-mrc-bridge', 'anetbbs-binkp',
                        'anetbbs-finger', 'anetbbs-web'):
                rendered = _render_heredoc(
                    script, unit, '/opt/anetbbs', '/opt/anetbbs/venv',
                    rw, ro)
                self.assertIn(
                    'ReadWritePaths=/opt/anetbbs/data /opt/anetbbs/logs',
                    rendered)
                self.assertNotIn('ReadOnlyPaths=', rendered)


if __name__ == '__main__':
    unittest.main()
